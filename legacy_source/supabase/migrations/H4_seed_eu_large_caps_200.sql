dedup as (
  select distinct on (symbol) symbol, name, exchange, currency, sector
  from seed
  order by symbol
),
picked as (
  select *
  from dedup
  order by symbol
  limit 200
)
insert into public.stocks (symbol, name, exchange, currency, sector, is_active, display_order)
select
  p.symbol,
  p.name,
  p.exchange,
  p.currency,
  p.sector,
  true,
  1000 + row_number() over (order by p.symbol)
from picked p
on conflict (symbol) do update set
  name = excluded.name,
  exchange = excluded.exchange,
  currency = excluded.currency,
  sector = excluded.sector,
  is_active = true;
